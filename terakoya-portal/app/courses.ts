const examByName = new Map(examCatalog.map((course) => [course.name, course.quarters]));
export const surveyCourses = courses.flatMap((name, index) => {
  const quarters = examByName.get(name);
  return quarters ? [{ id: String(index).padStart(2, "0"), name, quarters }] : [];
});
export const surveyCourseIds = new Set(surveyCourses.map((course) => course.id));

export function courseId(name: string) {
  return courses.indexOf(name).toString().padStart(2, "0");
}

export function courseName(id: string) {
  return courses[Number(id)] ?? "不明な科目";
}
